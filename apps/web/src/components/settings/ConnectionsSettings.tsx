export function ConnectionsSettings() {
  const primaryEnvironment = usePrimaryEnvironment();
  const primaryEnvironmentId = primaryEnvironment?.environmentId ?? null;
  const primarySessionState = usePrimarySessionState();
  const currentSessionScopes = primarySessionState.data?.authenticated
    ? (primarySessionState.data.permissions ?? primarySessionState.data.scopes ?? [])
    : [];
  const canReadAccess = useEnvironmentScope(primaryEnvironmentId, AuthAccessReadScope);
  const canWriteAccess = useEnvironmentScope(primaryEnvironmentId, AuthAccessWriteScope);
  const authAccessChanges = useEnvironmentQuery(
    canReadAccess && primaryEnvironmentId !== null
      ? authEnvironment.accessChanges({ environmentId: primaryEnvironmentId, input: null })
      : null,
  );
  const [desktopAccessManagementMutationError, setDesktopAccessManagementMutationError] = useState<
    string | null
  >(null);
  const [createdPairingCredentials, setCreatedPairingCredentials] = useState<
    ReadonlyMap<string, string>
  >(() => new Map());
  const handlePairingLinkCreated = useCallback((created: AuthPairingCredentialResult) => {
    setCreatedPairingCredentials((current) => new Map(current).set(created.id, created.credential));
  }, []);
  const [revokingDesktopPairingLinkId, setRevokingDesktopPairingLinkId] = useState<string | null>(
    null,
  );
  const [revokingDesktopClientSessionId, setRevokingDesktopClientSessionId] = useState<
    string | null
  >(null);
  const [isRevokingOtherDesktopClients, setIsRevokingOtherDesktopClients] = useState(false);
  const snapshot =
    authAccessChanges.data?.type === "snapshot" ? authAccessChanges.data.payload : null;
  const desktopPairingLinks = useMemo(
    () => sortDesktopPairingLinks(snapshot?.pairingLinks.map(toDesktopPairingLinkRecord) ?? []),
    [snapshot],
  );
  const desktopClientSessions = useMemo(
    () =>
      sortDesktopClientSessions(snapshot?.clientSessions.map(toDesktopClientSessionRecord) ?? []),
    [snapshot],
  );
  const handleRevokeDesktopPairingLink = useCallback(
    async (id: string) => {
      if (
        primaryEnvironmentId === null ||
        !readEnvironmentScope(primaryEnvironmentId, AuthAccessWriteScope)
      )
        return;
      setRevokingDesktopPairingLinkId(id);
      setDesktopAccessManagementMutationError(null);
      try {
        await revokeServerPairingLink(id);
      } catch (error) {
        const message = error instanceof Error ? error.message : "Failed to revoke pairing link.";
        setDesktopAccessManagementMutationError(message);
        toastManager.add(
          stackedThreadToast({
            type: "error",
            title: "Could not revoke pairing link",
            description: message,
          }),
        );
      } finally {
        setRevokingDesktopPairingLinkId(null);
      }
    },
    [primaryEnvironmentId],
  );

  const handleRevokeDesktopClientSession = useCallback(
    async (sessionId: ServerClientSessionRecord["sessionId"]) => {
      if (
        primaryEnvironmentId === null ||
        !readEnvironmentScope(primaryEnvironmentId, AuthAccessWriteScope)
      )
        return;
      setRevokingDesktopClientSessionId(sessionId);
      setDesktopAccessManagementMutationError(null);
      try {
        await revokeServerClientSession(sessionId);
      } catch (error) {
        const message = error instanceof Error ? error.message : "Failed to revoke client access.";
        setDesktopAccessManagementMutationError(message);
        toastManager.add(
          stackedThreadToast({
            type: "error",
            title: "Could not revoke client access",
            description: message,
          }),
        );
      } finally {
        setRevokingDesktopClientSessionId(null);
      }
    },
    [primaryEnvironmentId],
  );

  const handleRevokeOtherDesktopClients = useCallback(async () => {
    if (
      primaryEnvironmentId === null ||
      !readEnvironmentScope(primaryEnvironmentId, AuthAccessWriteScope)
    )
      return;
    setIsRevokingOtherDesktopClients(true);
    setDesktopAccessManagementMutationError(null);
    try {
      const revokedCount = await revokeOtherServerClientSessions();
      toastManager.add({
        type: "success",
        title: revokedCount === 1 ? "Revoked 1 other client" : `Revoked ${revokedCount} clients`,
        description: "Other paired clients will need a new pairing link before reconnecting.",
      });
    } catch (error) {
      const message = error instanceof Error ? error.message : "Failed to revoke other clients.";
      setDesktopAccessManagementMutationError(message);
      toastManager.add(
        stackedThreadToast({
          type: "error",
          title: "Could not revoke other clients",
          description: message,
        }),
      );
    } finally {
      setIsRevokingOtherDesktopClients(false);
    }
  }, [primaryEnvironmentId]);

  return (
    <SettingsPageContainer>
      <SettingsSection id="connections-environment" title="Central service">
        <SettingsRow
          title="Connection"
          description={
            primaryEnvironment ? connectionStatusText(primaryEnvironment.connection) : "Connecting…"
          }
        />
        <p className="px-4 py-3 text-xs text-muted-foreground">
          Projects and conversations stay in this service. New threads run in independent sandbox
          workspaces; delegated agents share their parent's workspace.
        </p>
        {primaryEnvironmentId ? (
          <details className="px-4">
            <summary className="cursor-pointer py-3 text-xs text-muted-foreground">
              Permissions
            </summary>
            <SessionPermissions
              environmentId={primaryEnvironmentId}
              connected={primaryEnvironment?.connection.phase === "connected"}
            />
          </details>
        ) : null}
      </SettingsSection>
      {canReadAccess || canWriteAccess ? (
        <FoldedSettingsSection
          id="authorized-clients"
          title="Authorized clients"
          summary={summarizeAuthorizedClients(desktopClientSessions, desktopPairingLinks)}
          control={
            canWriteAccess ? (
              <AuthorizedClientsHeaderAction
                delegatableScopes={currentSessionScopes}
                onPairingLinkCreated={handlePairingLinkCreated}
                clientSessions={
                  canReadAccess && authAccessChanges.error === null && snapshot
                    ? desktopClientSessions
                    : null
                }
                isRevokingOtherClients={isRevokingOtherDesktopClients}
                onRevokeOtherClients={handleRevokeOtherDesktopClients}
              />
            ) : undefined
          }
        >
          {(desktopAccessManagementMutationError ?? authAccessChanges.error) ? (
            <p className="px-4 py-3 text-xs text-destructive">
              {desktopAccessManagementMutationError ?? authAccessChanges.error}
            </p>
          ) : null}
          {canReadAccess ? (
            <ScrollArea
              scrollFade
              chainVerticalScroll
              className="max-h-[22.5rem]"
              data-testid="authorized-clients-scroll-area"
            >
              <PairingClientsList
                endpointUrl={null}
                endpoints={[]}
                defaultEndpointKey={null}
                isLoading={authAccessChanges.isPending && snapshot === null}
                pairingLinks={desktopPairingLinks}
                createdPairingCredentials={createdPairingCredentials}
                clientSessions={desktopClientSessions}
                revokingPairingLinkId={revokingDesktopPairingLinkId}
                revokingClientSessionId={revokingDesktopClientSessionId}
                onRevokePairingLink={handleRevokeDesktopPairingLink}
                onRevokeClientSession={handleRevokeDesktopClientSession}
                canRevoke={canWriteAccess}
              />
            </ScrollArea>
          ) : (
            <p className="px-4 py-3 text-xs text-muted-foreground">
              This connection can create access links but cannot view authorized clients.
            </p>
          )}
        </FoldedSettingsSection>
      ) : null}
      {primaryEnvironmentId ? <LoadBalancingSettings environmentId={primaryEnvironmentId} /> : null}
    </SettingsPageContainer>
  );
}
